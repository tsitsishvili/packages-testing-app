#!/usr/bin/env bash
# Sends a mix of API calls (happy paths and expected errors) so documentator and
# elastic-audit see real traffic. Usage: BASE=http://localhost:8000/api scripts/api-traffic.sh
set -u
BASE=${BASE:-http://localhost:8000/api}
TOKEN=""
PASS=$(openssl rand -hex 12)
EMAIL="api-traffic-$(date +%s)@example.test"
fails=0
OUT=$(mktemp); trap 'rm -f "$OUT"' EXIT

# call METHOD PATH [JSON] [EXPECTED] -> prints status, stores body in $BODY
call() {
  local method=$1 path=$2 data=${3:-} expect=${4:-2..}
  local args=(-s -o "$OUT" -w '%{http_code}' -X "$method" -H 'Accept: application/json')
  [ -n "$TOKEN" ] && args+=(-H "Authorization: Bearer $TOKEN")
  [ -n "$data" ] && args+=(-H 'Content-Type: application/json' -d "$data")
  local code; code=$(curl "${args[@]}" "$BASE$path")
  BODY=$(cat "$OUT")
  local mark=ok; [[ $code =~ ^$expect$ ]] || { mark=FAIL; fails=$((fails+1)); }
  printf '%-4s %-7s %-45s %s\n' "$mark" "$method" "$path" "$code"
  [ $mark = FAIL ] && echo "     ${BODY:0:200}"
  return 0
}

echo "--- auth"
call POST /register "{\"name\":\"API Traffic\",\"email\":\"$EMAIL\",\"password\":\"$PASS\",\"password_confirmation\":\"$PASS\"}" 201
call POST /login "{\"email\":\"$EMAIL\",\"password\":\"$PASS\"}" 200
TOKEN=$(jq -r .token <<<"$BODY")
call GET /user

echo "--- products v1"
ids=()
for i in 1 2 3; do
  call POST /products "{\"name\":\"Traffic product $i\",\"price\":$((i*10)).5,\"description\":\"Generated by api-traffic.sh\"}" 201
  ids+=("$(jq -r '.data.id // .id' <<<"$BODY")")
done
P=${ids[0]}
call GET /products
call GET "/products/search?filter%5Bname%5D=Traffic&sort=-price&page%5Bsize%5D=5"
call GET "/products/$P"
call PUT "/products/$P" '{"name":"Traffic product 1 (updated)","price":12.75}'
call GET "/products/$P/statistics"
call POST "/products/$P/publish" '{"channel":"web","notify_subscribers":false}'
call POST "/products/$P/sync"
call DELETE "/products/${ids[2]}"

echo "--- products v2"
call POST /v2/products '{"name":"Traffic v2 product","price":99.99}' 201
V2=$(jq -r '.data.id // .id' <<<"$BODY")
call GET /v2/products
call GET "/v2/products/$V2"
call PUT "/v2/products/$V2" '{"name":"Traffic v2 product (updated)","price":89.99}'
call GET "/v2/products/$V2/statistics"
call POST "/v2/products/$V2/sync"
call DELETE "/v2/products/$V2"

echo "--- orders"
call POST /orders "{\"currency\":\"USD\",\"priority\":2,\"items\":[{\"product_id\":$P,\"quantity\":2},{\"product_id\":${ids[1]},\"quantity\":1}],\"notes\":\"traffic\"}" 201
O=$(jq -r '.data.id // .id' <<<"$BODY")
call POST /orders "{\"currency\":\"EUR\",\"priority\":1,\"items\":[{\"product_id\":${ids[1]},\"quantity\":3}]}" 201
O2=$(jq -r '.data.id // .id' <<<"$BODY")
call GET /orders
# PHP's built-in server (php artisan serve) answers the QUERY method with 501 before Laravel sees it.
call QUERY /orders '{"currency":"USD","per_page":5}' '(2..|501)'
call GET "/orders/$O"
call PUT "/orders/$O" '{"notes":"updated by traffic","priority":3}'
call POST "/orders/$O/ship" '{"tracking_number":"RR123456789GB","carrier":"dhl","weight_grams":1200,"declared_value":45.55,"parcel_count":1,"origin_ip":"203.0.113.10"}'
call GET "/orders/$O/shipment"
call POST "/orders/$O/reconcile"
call POST "/orders/$O2/cancel"

echo "--- misc"
call POST /newsletter/subscribe '{"email":"traffic@example.test","frequency":"weekly","consent":true,"topics":["news"]}'
# The demo webhook randomly answers 422 to produce failed payment logs.
call POST /webhooks/stripe '{"id":"evt_test_traffic","type":"payment_intent.succeeded","livemode":false,"amount":4550,"currency":"usd"}' '(200|422)'

echo "--- expected errors"
call POST /products '{"name":"missing price"}' 422
call GET /products/999999 "" 404
call POST /orders '{"currency":"XXX","priority":9,"items":[]}' 422
T=$TOKEN; TOKEN=""; call GET /user "" 401; TOKEN=$T

echo "--- logout"
call POST /logout
echo "done: $fails unexpected"
[ "$fails" -eq 0 ]
